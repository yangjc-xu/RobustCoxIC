## -----------------------------
## 2. Helper function for fitting the working Cox model
## -----------------------------

fit_working_cox_for_m <- function(SimData, eps = 0.001) {
  prepared <- prepare_data(SimData)
  X_mat <- as.matrix(SimData[, c("X1", "X2")])
  
  model <- unireg_indep_EM_improved(X_mat, prepared$simpdat, eps, prepared$Time)
  
  list(
    model = model,
    Time = prepared$Time,
    beta_hat = as.numeric(model$beta),
    lambda_hat = as.numeric(model$lambda),
    cumulative_lambda_hat = as.numeric(model$cumulative_lambda)
  )
}

## -----------------------------
## 3. Evaluate fitted Lambda at arbitrary U values
## -----------------------------
## The fitted Lambda is a step function. For plotting a population-level
## diagnostic curve, linear interpolation often gives a smoother approximation
## to the underlying Lambda_0^*. Set method = "step" if you want the exact
## finite-sample NPMLE step function.

eval_cumhaz <- function(t_vec, time_desc, cumhaz_desc,
                        method = c("linear", "step")) {
  method <- match.arg(method)
  
  time_asc <- rev(as.numeric(time_desc))
  cumhaz_asc <- rev(as.numeric(cumhaz_desc))
  
  keep <- !duplicated(time_asc)
  time_asc <- time_asc[keep]
  cumhaz_asc <- cumhaz_asc[keep]
  
  if (method == "linear") {
    x <- c(0, time_asc)
    y <- c(0, cumhaz_asc)
    out <- approx(x = x, y = y, xout = t_vec, method = "linear",
                  rule = 2, ties = "ordered")$y
    out[t_vec <= 0] <- 0
    return(out)
  }
  
  if (method == "step") {
    idx <- findInterval(t_vec, time_asc)
    out <- ifelse(idx == 0, 0, cumhaz_asc[idx])
    out[t_vec <= 0] <- 0
    return(out)
  }
}

## -----------------------------
## 4. Compute D_k^*(y), W_k^*(y), and m(y | U, K)
## -----------------------------

stable_s_over_expm1 <- function(s) {
  out <- numeric(length(s))
  
  small <- abs(s) < 1e-7
  large <- s > 700
  mid <- !(small | large)
  
  ## expansion: s / (exp(s) - 1) = 1 - s/2 + s^2/12 + o(s^2)
  out[small] <- 1 - s[small] / 2 + s[small]^2 / 12
  out[large] <- 0
  out[mid] <- s[mid] / expm1(s[mid])
  
  out
}

compute_D_matrix <- function(y_grid, A_U) {
  ## A_U = (Lambda(U_0), Lambda(U_1), ..., Lambda(U_K))
  ## with U_0 = 0. There are K+1 observed intervals:
  ## (U_0,U_1], ..., (U_{K-1},U_K], (U_K, infinity).
  
  K <- length(A_U) - 1
  n_y <- length(y_grid)
  ey <- exp(y_grid)
  
  D <- matrix(NA_real_, nrow = n_y, ncol = K + 1)
  colnames(D) <- paste0("D", 0:K)
  
  ## k = 0, ..., K-1 finite intervals
  for (k in 0:(K - 1)) {
    A_k <- A_U[k + 1]
    delta_k <- A_U[k + 2] - A_U[k + 1]
    
    if (delta_k <= 0) {
      warning("Some fitted Lambda increments over fixed U intervals are nonpositive. ",
              "A tiny ridge is added for numerical plotting. ",
              "Try method='linear', a larger n_fit, or another U_fixed.")
      delta_k <- 1e-8
    }
    
    s <- delta_k * ey
    D[, k + 1] <- -A_k * ey + stable_s_over_expm1(s)
  }
  
  ## k = K, last interval (U_K, infinity)
  A_K <- A_U[K + 1]
  D[, K + 1] <- -A_K * ey
  
  D
}

H_AFT <- function(t, y, sigma2) {
  sigma <- sqrt(sigma2)
  1 - pnorm((log(t) + y) / sigma)
}

compute_m_curve <- function(y_grid, U_fixed, fit_obj, sigma2,
                            lambda_eval_method = "linear") {
  K <- length(U_fixed)
  
  Lambda_U <- eval_cumhaz(
    t_vec = U_fixed,
    time_desc = fit_obj$Time,
    cumhaz_desc = fit_obj$cumulative_lambda_hat,
    method = lambda_eval_method
  )
  
  A_U <- c(0, Lambda_U)
  D <- compute_D_matrix(y_grid, A_U)
  
  ## W_k^*(y) = D_k^*(y) - D_{k-1}^*(y), k = 1,...,K
  W <- D[, 2:(K + 1), drop = FALSE] - D[, 1:K, drop = FALSE]
  
  H_mat <- sapply(U_fixed, function(u) H_AFT(u, y_grid, sigma2))
  
  ## m(y | U,K) = D_0^*(y) + sum_{k=1}^K H(U_k | y) W_k^*(y)
  m_val <- D[, 1] + rowSums(H_mat * W)
  
  data.frame(
    y = y_grid,
    m = as.numeric(m_val),
    sigma2 = sigma2
  )
}

