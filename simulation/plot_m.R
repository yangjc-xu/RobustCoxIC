set.seed(20260607)

## Use 2000 for speed. Increase to 5000 or 10000 for a smoother approximation
## to the population pseudo-true Lambda_0^*.
n_fit <- 10000

dat_small <- sim_data_ratio(n_fit, model = 6)
dat_large <- sim_data_ratio(n_fit, model = 5)

fit_small <- fit_working_cox_for_m(dat_small, eps = 0.001)
fit_large <- fit_working_cox_for_m(dat_large, eps = 0.001)

cat("\nEstimated beta, small variance sigma^2=0.5:\n")
print(fit_small$beta_hat)

cat("\nEstimated beta, large variance sigma^2=2:\n")
print(fit_large$beta_hat)

beta0 <- c(0.5, 1)
alpha_small_hat <- sum(beta0 * fit_small$beta_hat) / sum(beta0^2)
alpha_large_hat <- sum(beta0 * fit_large$beta_hat) / sum(beta0^2)

cat("\nApproximate alpha_hat, small variance sigma^2=0.5:\n")
print(alpha_small_hat)

cat("\nApproximate alpha_hat, large variance sigma^2=2:\n")
print(alpha_large_hat)

## Fixed examination times U_1,...,U_6.
## You can replace this by any fixed subject-specific U vector.
U_fixed <- c(0.15, 0.5, 1, 2.5, 4, 5.5)

## Natural plotting range for Y = 0.5 X1 + X2.
Sigma_X <- matrix(c(1, 0.3,
                    0.3, 1), nrow = 2)
sd_Y <- sqrt(as.numeric(t(beta0) %*% Sigma_X %*% beta0))

y_grid <- seq(
  from = qnorm(0.005, mean = 0, sd = sd_Y),
  to   = qnorm(0.995, mean = 0, sd = sd_Y),
  length.out = 500
)

curve_small <- compute_m_curve(
  y_grid = y_grid,
  U_fixed = U_fixed,
  fit_obj = fit_small,
  sigma2 = 0.5,
  lambda_eval_method = "linear"
)
curve_small$model <- expression_text <- "small error variance: sigma^2 = 0.5"

curve_large <- compute_m_curve(
  y_grid = y_grid,
  U_fixed = U_fixed,
  fit_obj = fit_large,
  sigma2 = 2,
  lambda_eval_method = "linear"
)
curve_large$model <- "large error variance: sigma^2 = 2"

plot_dat <- rbind(curve_small, curve_large)

## Simple monotonicity check on the selected y-grid.
monotonic_summary <- do.call(
  rbind,
  lapply(split(plot_dat, plot_dat$model), function(d) {
    dm <- diff(d$m)
    data.frame(
      model = unique(d$model),
      min_diff = min(dm),
      max_diff = max(dm),
      monotonicity_on_grid =
        if (all(dm >= -1e-6)) {
          "nondecreasing"
        } else if (all(dm <= 1e-6)) {
          "nonincreasing"
        } else {
          "not monotone on this grid"
        }
    )
  })
)

